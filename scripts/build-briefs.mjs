// Bundles every src/lib/briefs/<slug>.md into src/lib/briefs/generated.ts,
// so the /api/briefs route serves them without reading files at runtime.
// Run after adding or editing a brief: `npm run briefs`. Commit both files.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src", "lib", "briefs");
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => {
    const slug = f.replace(/\.md$/, "");
    if (!/^[a-z0-9-]{1,80}$/.test(slug)) throw new Error(`bad brief slug: ${slug}`);
    return [slug, readFileSync(join(dir, f), "utf8")];
  });

const body = entries
  .map(([slug, md]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(md)},`)
  .join("\n");

writeFileSync(
  join(dir, "generated.ts"),
  `// Generated by scripts/build-briefs.mjs from src/lib/briefs/*.md. Don't edit.\n` +
    `export const BRIEFS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`briefs: ${entries.map(([s]) => s).join(", ") || "(none)"}`);
